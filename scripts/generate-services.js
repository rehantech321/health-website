#!/usr/bin/env node
// Generates lib/server/services.ts from the SERVICES / CATS arrays inside
// public/eldava-app.js, so the server-side price list - the one every booking
// is actually charged against - can never disagree with what the UI shows.
// Re-run whenever SERVICES changes in eldava-app.js:  node scripts/generate-services.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const script = fs.readFileSync(path.join(root, 'public', 'eldava-app.js'), 'utf8');

const svcMatch = script.match(/var SERVICES = (\[[\s\S]*?\n\s*\]);/);
const catMatch = script.match(/var CATS = (\{[\s\S]*?\});/);
if (!svcMatch || !catMatch) throw new Error('Could not locate SERVICES / CATS in public/eldava-app.js');

const SERVICES = eval(svcMatch[1]);
const CATS = eval('(' + catMatch[1] + ')');

function durationMin(dur) {
  const m = /^(\d+)\s*min/.exec(dur);
  return m ? Number(m[1]) : 60;
}

const j = JSON.stringify;
const lines = SERVICES.map(
  (s) =>
    `  { name: ${j(s.name)}, cat: ${j(s.cat)}, desc: ${j(s.desc)}, priceMinor: ${s.price * 100}, durationLabel: ${j(s.dur)}, durationMin: ${durationMin(s.dur)} },`
);

const out = `// GENERATED by scripts/generate-services.js from public/eldava-app.js.
// Do not edit by hand - change SERVICES in eldava-app.js and re-run the script.
//
// Prices are in PENCE. The browser is never trusted for a price: every booking
// looks the service up here by name and charges this figure.

export type Service = {
  name: string;
  cat: string;
  desc: string;
  priceMinor: number;
  durationLabel: string;
  durationMin: number;
};

export const CATEGORIES: Record<string, string> = ${JSON.stringify(CATS, null, 2)};

/// Category of the Founding 500 prepaid vouchers - bought now, redeemed later,
/// so they bypass slot selection and count toward the 500 cap.
export const FOUNDING_CAT = 'founding';
export const FOUNDING_CAP = 500;

export const SERVICES: Service[] = [
${lines.join('\n')}
];

const BY_NAME = new Map(SERVICES.map((s) => [s.name, s]));

/// Catalogue entry for a service name, or null if it is not something we sell.
export function findService(name: unknown): Service | null {
  return BY_NAME.get(String(name ?? '').trim()) ?? null;
}

export function isVoucher(service: Service): boolean {
  return service.cat === FOUNDING_CAT;
}

/// Formats pence as GBP, e.g. 68500 -> "£685".
export function formatMinor(minor: number): string {
  return '£' + Math.round(minor / 100).toLocaleString('en-GB');
}
`;

const target = path.join(root, 'lib', 'server', 'services.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out, 'utf8');
console.log(`Wrote ${SERVICES.length} services / ${Object.keys(CATS).length} categories to lib/server/services.ts`);
